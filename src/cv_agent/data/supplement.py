class DataSupplementer:
    """Handles data deficiency resolution with script generation and user interaction."""

    def __init__(self, interaction: SupplementInteraction | None = None) -> None:
        self._interaction = interaction

    def handle(
        self,
        issues: list[ValidationIssue],
        run_dir: Path,
    ) -> bool:
        """Handle validation issues - generate scripts and/or wait for user.

        Returns:
            True if validation should be retried (e.g. the user fixed the data
            in ask mode and confirmed a retry); False if the engine should
            abort. Auto mode always returns False — an unattended run cannot
            fix missing data by re-validating in a tight loop, so we generate
            the scripts and let the engine exit cleanly instead of spinning.
        """
        print_validation_issues([i.model_dump() for i in issues])

        errors = [i for i in issues if i.severity == "error"]
        warnings = [i for i in issues if i.severity == "warning"]

        log_warning(f"Found {len(errors)} error(s) and {len(warnings)} warning(s) in dataset.")

        # Determine which classes are affected
        affected_classes: list[str] = []
        for issue in issues:
            if issue.category == "class_count":
                detail = issue.detail
                if "Class '" in detail:
                    cls_name = detail.split("'")[1]
                    if cls_name not in affected_classes:
                        affected_classes.append(cls_name)

        # Generate supplement scripts
        script_count = 0
        output_data_dir = run_dir / "supplemented_data"

        if affected_classes:
            script = _generate_roboflow_script(affected_classes, output_data_dir)
            save_supplement_script(run_dir, "roboflow_download.py", script)
            script_count += 1

            script = _generate_openimages_script(affected_classes, output_data_dir)
            save_supplement_script(run_dir, "openimages_download.sh", script)
            script_count += 1

            script = _generate_huggingface_script(affected_classes, output_data_dir)
            save_supplement_script(run_dir, "huggingface_download.py", script)
            script_count += 1

        if any(i.category in ("missing_annotations", "orphan_labels") for i in issues):
            script = _generate_annotation_suggestion()
            save_supplement_script(run_dir, "annotation_tools.md", script)
            script_count += 1

        if script_count > 0:
            log_info(f"Generated {script_count} supplement script(s) in {run_dir / 'supplement_scripts/'}")

        # Interaction: ask mode lets the user fix data and retry; auto mode
        # cannot, so abort after generating the scripts.
        from cv_agent.interaction.auto_mode import AutoModeHandler

        if self._interaction is not None and not isinstance(self._interaction, AutoModeHandler):
            try:
                retry = self._interaction.confirm_supplement([i.model_dump() for i in issues])
            except SessionQuit:
                raise
            return bool(retry)

        log_error(
            "Auto mode: dataset validation failed and cannot be auto-resolved. "
            "Run the generated supplement scripts, add the data, then re-run cv_agent."
        )
        return False